const profile = document.getElementById('profile-account');
const popup   = document.getElementById('profile-popup');

profile.addEventListener('click', (e) => {
  e.stopPropagation();         // чтобы клик не дошёл до document

  // ставим окошко под картинкой
  const rect = profile.getBoundingClientRect();
  popup.style.left = rect.left + window.scrollX + 'px';
  popup.style.top  = rect.bottom + window.scrollY + 8 + 'px';

  popup.classList.toggle('open');
});

// клик вне окошка — закрыть
document.addEventListener('click', (e) => {
  if (!popup.contains(e.target) && e.target !== profile) {
    popup.classList.remove('open');
  }
});

// Esc — закрыть
document.addEventListener('keydown', (e) => {
  if (e.key === 'Escape') popup.classList.remove('open');
});

// Добавление данных в профиль пользователя 
  const form = document.getElementById('form');
  const info = document.getElementById('profile-info');
  const editBtn = document.getElementById('edit-btn');

  // 1. Отрисовка данных в попапе
  function renderProfile(data) {
    info.innerHTML = `
      <p>Full Name: ${data.fullname || '—'}</p>
      <p>Nick Name: ${data.nickname || '—'}</p>
      <p>Gender: ${data.gender || '—'}</p>
      <p>Country: ${data.country || '—'}</p>
      <p>Language: ${data.language || '—'}</p>
      <p>Time Zone: ${data.timezone || '—'}</p>`
  }

  // 2. Заполнение формы сохранёнными данными
  function fillForm(data) {
    for (const key in data) {
      const field = form.elements[key];
      if (field) field.value = data[key];
    }
  }

  // 3. Кнопка Edit: сохранить + показать
  editBtn.addEventListener('click', () => {
    const data = Object.fromEntries(new FormData(form).entries());

    localStorage.setItem('profile', JSON.stringify(data));
    renderProfile(data);                            
  });

  // 4. При загрузке страницы: достаём из localStorage
  window.addEventListener('DOMContentLoaded', () => {
    const saved = localStorage.getItem('profile');
    if (saved) {
      const data = JSON.parse(saved);
      fillForm(data);       
      renderProfile(data); 
    }
  })
